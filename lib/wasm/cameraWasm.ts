export type CameraVectors = {
  pos: [number, number, number];
  look: [number, number, number];
};

type WasmApi = {
  compute: (t: number, phase: number, mouseX: number, mouseY: number, scroll: number, reduced: boolean) => CameraVectors;
};

let wasmApiPromise: Promise<WasmApi | null> | null = null;

function computeCameraJs(
  t: number,
  phase: number,
  mouseX: number,
  mouseY: number,
  scroll: number,
  reduced: boolean
): CameraVectors {
  if (reduced) {
    return { pos: [0, 0.3, 9.2], look: [0, -0.1, 0] };
  }

  let tx = 0.2 + mouseX * 0.4;
  let ty = 0.35 + mouseY * 0.25;
  let tz = 8.6;
  let lx = 0;
  let ly = -0.1;
  let lz = 0;

  if (phase === 0) {
    tx = 0.8 + Math.sin(t * 0.7) * 0.08;
    ty = 0.45;
    tz = 3.8;
    lx = 0.15;
    ly = 0.35;
    lz = 0.8;
  } else if (phase === 1) {
    const p = Math.max(0, Math.min(1, (t - 2.2) / 4.8));
    const orbit = p * 0.35;
    tx = 0.8 + (-0.6 - 0.8) * p + Math.sin(orbit) * 0.6 + mouseX * 0.25;
    ty = 0.45 + (0.4 - 0.45) * p + mouseY * 0.15;
    tz = 3.8 + (7.2 - 3.8) * p;
    lx = 0.15 + (0 - 0.15) * p;
    ly = 0.2 + (-0.05 - 0.2) * p;
    lz = 0;
  } else if (phase === 2) {
    tx = -0.2 + mouseX * 0.35;
    ty = 0.5 + mouseY * 0.2;
    tz = 8.0;
    lx = 0;
    ly = 0;
    lz = 0;
  } else {
    tx = mouseX * 0.55;
    ty = 0.35 + mouseY * 0.3;
    tz = 8.8 - scroll * 3.8;
    lx = 0;
    ly = -0.05 + scroll * 0.4;
    lz = 0;
  }

  return { pos: [tx, ty, tz], look: [lx, ly, lz] };
}

async function loadWasmApi(): Promise<WasmApi | null> {
  if (typeof window === 'undefined') return null;
  try {
    // Generated by: bash wasm/build.sh (Emscripten) and served from /public/wasm/
    const wasmModuleUrl = '/wasm/camera_path.js';
    const mod = await (Function('u', 'return import(u)') as (u: string) => Promise<any>)(wasmModuleUrl);
    const factory = mod.default ?? mod;
    const instance = await factory({
      locateFile: (path: string) => (path.endsWith('.wasm') ? `/wasm/${path}` : path),
    });

    const computeCamera = instance.cwrap('computeCamera', null, [
      'number', // t
      'number', // phase
      'number', // mouseX
      'number', // mouseY
      'number', // scroll
      'number', // reduced
      'number', // pos ptr
      'number', // look ptr
    ]);

    const posPtr = instance._malloc(12); // 3 * float32
    const lookPtr = instance._malloc(12);

    return {
      compute: (t, phase, mouseX, mouseY, scroll, reduced) => {
        computeCamera(t, phase, mouseX, mouseY, scroll, reduced ? 1 : 0, posPtr, lookPtr);
        const heap = instance.HEAPF32 as Float32Array;
        const pBase = posPtr >> 2;
        const lBase = lookPtr >> 2;
        return {
          pos: [heap[pBase], heap[pBase + 1], heap[pBase + 2]],
          look: [heap[lBase], heap[lBase + 1], heap[lBase + 2]],
        };
      },
    };
  } catch {
    return null;
  }
}

export async function getCameraComputer(): Promise<(t: number, phase: number, mouseX: number, mouseY: number, scroll: number, reduced: boolean) => CameraVectors> {
  if (!wasmApiPromise) wasmApiPromise = loadWasmApi();
  const api = await wasmApiPromise;
  if (api) return api.compute;
  return computeCameraJs;
}